"""Generates the synthetic "trust in science" item responses used by /indices (09 Building an Index).

Every value is synthetic. 120 respondents answer six 1-5 agreement items: four are worded in the
"trusting" direction, two (T3, T5) in the opposite direction and must be reverse-scored, and one (T6)
measures interest in science rather than trust, so it fits the index poorly. The generator is seeded
and searches seeds until the teaching targets below hold, so that every number quoted on the page is
computed from these data.

Run:  python3 scripts/indices/generate.py    (writes src/components/modules/indices/responses.ts)
Then: python3 scripts/validation/reference.py (writes the reference values checked by the unit tests)
"""

import json
from pathlib import Path

import numpy as np

N = 120
LOADINGS = [0.95, 0.85, -0.8, 0.75, -0.9, 0.2]  # T3, T5 negative: opposite wording; T6 barely related
REVERSED = [2, 4]


def alpha(m: np.ndarray) -> float:
    k = m.shape[1]
    return k / (k - 1) * (1 - m.var(0, ddof=1).sum() / m.sum(1).var(ddof=1))


def item_total(m: np.ndarray) -> list[float]:
    tot = m.sum(1)
    return [float(np.corrcoef(m[:, j], tot - m[:, j])[0, 1]) for j in range(m.shape[1])]


def alpha_if_deleted(m: np.ndarray) -> list[float]:
    return [alpha(np.delete(m, j, 1)) for j in range(m.shape[1])]


def draw(seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    trust = rng.normal(0.6, 1, N)  # the sample leans trusting
    interest = rng.normal(0, 1, N)
    cols = []
    for j, l in enumerate(LOADINGS):
        latent = l * trust + (0.9 * interest if j == 5 else 0) + rng.normal(0, 0.85, N)
        cols.append(np.clip(np.round(3 + 1.05 * latent), 1, 5))
    return np.array(cols, dtype=int).T


def targets(raw: np.ndarray) -> bool:
    rev = raw.copy()
    rev[:, REVERSED] = 6 - rev[:, REVERSED]
    a6 = alpha(rev)
    aid6 = alpha_if_deleted(rev)
    it6 = item_total(rev)
    five = np.delete(rev, 5, 1)
    a5 = alpha(five)
    aid5 = alpha_if_deleted(five)
    half = raw.copy()
    half[:, 2] = 6 - half[:, 2]  # T5 forgotten
    return (
        alpha(raw) < 0.2
        and 0.66 <= a6 < 0.70  # "questionable": just misses .70 with all six items
        and int(np.argmax(aid6)) == 5 and aid6[5] > 0.76
        and it6[5] < 0.2 and min(it6[:5]) > 0.45
        and max(aid5) < a5  # after dropping T6 nothing else helps
        and item_total(half)[4] < 0
        and all(len(set(raw[:, j])) == 5 for j in range(6))
    )


if __name__ == "__main__":
    seed = next(s for s in range(1, 100000) if targets(draw(s)))
    data = draw(seed)
    rev = data.copy()
    rev[:, REVERSED] = 6 - rev[:, REVERSED]
    print("seed", seed, "alpha raw", round(alpha(data), 3), "alpha 6", round(alpha(rev), 3),
          "alpha 5", round(alpha(np.delete(rev, 5, 1)), 3))
    print("item-total", np.round(item_total(rev), 3), "alpha if deleted", np.round(alpha_if_deleted(rev), 3))
    out = Path(__file__).resolve().parents[2] / "src/components/modules/indices/responses.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// Generated by scripts/indices/generate.py: synthetic answers of 120 respondents to items T1-T6 (1-5).\n"
        "// Do not edit by hand; regenerate and rerun scripts/validation/reference.py instead.\n"
        f"export const RESPONSES: number[][] = {json.dumps(data.tolist(), separators=(',', ':'))};\n"
    )
    print("wrote", out)
